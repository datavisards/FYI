/**
 * Cut the favicon and the extension icons from the FYI mark's geometry.
 *
 *   node extension/icons/build-icons.mjs      (run from the repo root)
 *
 * Writes src/app/icon.svg, src/app/icon.png, src/app/apple-icon.png and
 * extension/icons/icon{16,48,128}.png.
 *
 * The geometry is duplicated from src/components/brand/FyiMark.tsx and
 * public/fyi-mark.svg. Literal hex only, because librsvg (which sharp uses to
 * rasterise) resolves neither CSS var() nor oklch(), and silently paints black
 * when it meets either.
 *
 * Uses sharp, which is present via Next's dependency tree rather than declared
 * in package.json. If that ever stops being true, `npm i -D sharp`.
 */
import sharp from 'sharp'
import { writeFileSync } from 'node:fs'

const WORD =
  'M7.31 0.00V-72.75H53.89V-61.77H20.35V-39.93H50.64V-29.09H20.35V0.00Z M85.60 0.00V-28.17L58.72 ' +
  '-72.75H73.95L86.95 -49.81Q89.02 -46.21 90.62 -42.78Q92.23 -39.35 93.94 -34.41H90.52Q92.19 ' +
  '-39.41 93.78 -42.87Q95.37 -46.33 97.33 -49.81L110.05 -72.75H125.21L98.61 -28.17V0.00Z ' +
  'M145.48 -72.75V0.00H132.44V-72.75Z'
const DASH_X = [20.64, 58.76, 96.87, 134.99]
const MARK = { x: 20.64, w: 138.17, h: 96.6, ruleY: 83.6, ruleH: 13, dashW: 23.82 }

// The app's tokens resolved to sRGB. The rule runs at full strength here, not the
// header's 50%: at 16px a half-strength rule disappears.
const INK_LIGHT = '#0a0a0a' // foreground
const INK_DARK = '#fafafa' // foreground, dark
const RULE_LIGHT = '#737373' // muted-foreground
const RULE_DARK = '#a3a3a3' // muted-foreground, dark

/** The mark scaled into a 100x100 square, `pad` either side, centred vertically. */
function art(inkAttr, ruleAttr, pad) {
  const s = (100 - 2 * pad) / MARK.w
  const tx = pad - MARK.x * s
  const ty = (100 - MARK.h * s) / 2
  const dashes = DASH_X.map(
    (x) => `<rect x="${x}" y="${MARK.ruleY}" width="${MARK.dashW}" height="${MARK.ruleH}" rx="2"/>`
  ).join('')
  return `  <g transform="translate(${tx.toFixed(3)} ${ty.toFixed(3)}) scale(${s.toFixed(5)})">
    <path ${inkAttr} transform="translate(13.33 72.75)" d="${WORD}"/>
    <g ${ruleAttr}>${dashes}</g>
  </g>`
}

/** Opaque rounded tile, for the raster contexts that cannot adapt to a theme. */
const tile = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100" width="100" height="100">
  <rect width="100" height="100" rx="22" fill="${INK_LIGHT}"/>
${art(`fill="${INK_DARK}"`, `fill="${RULE_DARK}"`, 12)}
</svg>
`

/** Transparent and theme-adaptive, for the browser tab. */
const adaptive = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100" width="100" height="100" role="img" aria-label="FYI">
  <title>FYI</title>
  <!--
    Generated by extension/icons/build-icons.mjs. Do not edit by hand.

    Transparent, so it sits on whatever the tab strip is, and it swaps ink on
    prefers-color-scheme, which Chrome and Firefox honour for SVG favicons.
  -->
  <style>
    .ink { fill: ${INK_LIGHT}; }
    .rule { fill: ${RULE_LIGHT}; }
    @media (prefers-color-scheme: dark) {
      .ink { fill: ${INK_DARK}; }
      .rule { fill: ${RULE_DARK}; }
    }
  </style>
${art('class="ink"', 'class="rule"', 8)}
</svg>
`

writeFileSync('src/app/icon.svg', adaptive)
console.log('wrote src/app/icon.svg')

for (const [out, size] of [
  ['extension/icons/icon16.png', 16],
  ['extension/icons/icon48.png', 48],
  ['extension/icons/icon128.png', 128],
  ['src/app/icon.png', 32],
  ['src/app/apple-icon.png', 180],
]) {
  await sharp(Buffer.from(tile), { density: 72 * (size / 100) * 8 })
    .resize(size, size)
    .png()
    .toFile(out)
  console.log('wrote', out, `${size}x${size}`)
}
